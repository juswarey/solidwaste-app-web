-- Delete rules. An older setup used ON DELETE CASCADE here, so deleting a Barangay Admin,
-- a waste category or a zone silently deleted zones, schedules and their pickup history.
-- These are replaced with RESTRICT (or SET NULL for pickup history), as in the PHP version.
create or replace function pg_temp.set_fk(p_table text, p_column text, p_ref text, p_ref_col text, p_action text)
returns void language plpgsql as $$
declare
  c record;
  v_ok boolean := false;
  v_want "char" := case p_action when 'restrict' then 'r' when 'set null' then 'n' end;
begin
  for c in
    select con.conname, con.confdeltype
    from pg_constraint con
    join pg_attribute a on a.attrelid = con.conrelid and a.attnum = any (con.conkey)
    where con.contype = 'f' and con.conrelid = ('public.' || p_table)::regclass
      and a.attname = p_column and array_length(con.conkey, 1) = 1
  loop
    if c.confdeltype = v_want and not v_ok then
      v_ok := true;                       -- already right; keep this one
    else
      execute format('alter table public.%I drop constraint %I', p_table, c.conname);
    end if;
  end loop;
  if not v_ok then
    execute format('alter table public.%I add constraint %I foreign key (%I) references public.%I (%I) on update cascade on delete %s',
                   p_table, p_table || '_' || p_column || '_fkey', p_column, p_ref, p_ref_col, p_action);
  end if;
end $$;
select pg_temp.set_fk('route', 'barangay_admin_id', 'barangay_admin', 'barangay_admin_id', 'restrict');
select pg_temp.set_fk('collection_schedule', 'waste_category_id', 'waste_category', 'waste_category_id', 'restrict');
select pg_temp.set_fk('collection_schedule', 'barangay_admin_id', 'barangay_admin', 'barangay_admin_id', 'restrict');
select pg_temp.set_fk('collection_schedule', 'route_id', 'route', 'route_id', 'restrict');
select pg_temp.set_fk('pickup_log', 'garbage_collector_id', 'garbage_collector', 'garbage_collector_id', 'set null');

-- Tell the API about the changes.
notify pgrst, 'reload schema';
