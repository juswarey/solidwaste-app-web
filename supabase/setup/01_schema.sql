-- =====================================================================
-- ECollect | Supabase setup 1 of 4: tables
-- Run in Supabase -> SQL Editor, in order 01 -> 03, then ONE of:
--   04_data.sql              a NEW, empty project (loads the Barangay Poblacion data), or
--   04_upgrade_existing.sql  a project that already has ECollect data (keeps every row).
-- Same tables and columns as the PHP/MySQL version, plus auth_user_id
-- links to Supabase Auth (logins live in Supabase Auth, not in these tables).
-- Safe to re-run, and safe on an existing project: tables are only created when
-- missing, and the section at the end adds missing columns and fixes delete rules.
-- =====================================================================

-- ---------- People ----------
create table if not exists public.lgu_admin (
  lgu_admin_id  integer generated by default as identity primary key,
  email         varchar(100) not null unique,
  first_name    varchar(50),
  last_name     varchar(50),
  auth_user_id  uuid unique references auth.users (id) on delete set null,
  created_at    timestamptz not null default now()
);

create table if not exists public.barangay_admin (
  barangay_admin_id integer generated by default as identity primary key,
  firstname     varchar(100),
  lastname      varchar(100),
  email         varchar(150) unique,
  auth_user_id  uuid unique references auth.users (id) on delete set null,
  created_at    timestamptz not null default now()
);

create table if not exists public.truck (
  truck_id        integer generated by default as identity primary key,
  plate_number    varchar(20) not null unique,
  max_capacity_kg numeric(10,2)
);

-- ---------- Zones (Barangay Poblacion has exactly 10; see 03_logic.sql) ----------
-- A zone is a row of `route` (the mobile app uses route_id as the zone).
create table if not exists public.route (
  route_id             integer generated by default as identity primary key,
  zone_name            varchar(50),
  path_coordinates     text,          -- JSON: [{"latitude":..,"longitude":..}, ...]
  boundary_coordinates text,          -- JSON, same format (traced zone area)
  boundary_source      varchar(255),
  barangay_admin_id    integer references public.barangay_admin (barangay_admin_id) on update cascade on delete restrict,
  collection_days      varchar(100),  -- "Monday,Wednesday,Friday"
  start_time           time,
  end_time             time,
  collection_mode      varchar(20) not null default 'truck' check (collection_mode in ('truck', 'drop_off'))
);

create table if not exists public.waste_category (
  waste_category_id   integer generated by default as identity primary key,
  category_name       varchar(100) not null,
  disposal_guidelines text
);

create table if not exists public.garbage_collector (
  garbage_collector_id integer generated by default as identity primary key,
  route_id      integer references public.route (route_id) on update cascade on delete set null,
  truck_id      integer references public.truck (truck_id) on update cascade on delete set null,
  email         varchar(100) not null unique,
  first_name    varchar(50) not null,
  last_name     varchar(50) not null,
  auth_user_id  uuid unique references auth.users (id) on delete set null,
  created_at    timestamptz not null default now()
);

create table if not exists public.resident (
  resident_id    integer generated by default as identity primary key,
  email          varchar(100) not null unique,
  first_name     varchar(50) not null,
  last_name      varchar(50) not null default '',
  contact_number varchar(20),
  home_address   text,
  route_id       integer references public.route (route_id) on update cascade on delete set null,
  auth_user_id   uuid unique references auth.users (id) on delete cascade,
  created_at     timestamptz not null default now()
);

-- ---------- Fixed schedule: truck stops ----------
create table if not exists public.collection_point (
  collection_point_id integer generated by default as identity primary key,
  name               varchar(120) not null unique,
  landmark           varchar(160),
  route_id           integer references public.route (route_id) on update cascade on delete set null,  -- zone where the stop is
  latitude           numeric(10,8),
  longitude          numeric(11,8),
  location_source    varchar(255),
  location_confirmed boolean not null default false,
  maps_url           varchar(1000),
  collection_days    varchar(100),
  start_time         time,
  end_time           time,
  standby_minutes    integer,
  stop_order         integer not null default 1,
  is_active          boolean not null default true,
  updated_at         timestamptz not null default now()
);

create table if not exists public.collection_point_zone (
  collection_point_id integer not null references public.collection_point (collection_point_id) on update cascade on delete cascade,
  route_id            integer not null references public.route (route_id) on update cascade on delete cascade,
  primary key (collection_point_id, route_id)
);

-- One row per zone per weekday. 'fixed' rows are kept in sync with the truck stops.
create table if not exists public.collection_schedule (
  collection_schedule_id integer generated by default as identity primary key,
  waste_category_id    integer references public.waste_category (waste_category_id) on update cascade on delete restrict,
  day_of_week          varchar(20),
  schedule_status      varchar(50),
  barangay_admin_id    integer references public.barangay_admin (barangay_admin_id) on update cascade on delete restrict,
  garbage_collector_id integer references public.garbage_collector (garbage_collector_id) on update cascade on delete set null,
  route_id             integer references public.route (route_id) on update cascade on delete restrict,
  start_time           time,
  end_time             time,
  schedule_type        varchar(20) not null default 'custom' check (schedule_type in ('fixed', 'custom')),
  collection_point_id  integer references public.collection_point (collection_point_id) on update cascade on delete set null,
  effective_from       date
);
create index if not exists cs_route_day on public.collection_schedule (route_id, day_of_week);
create index if not exists cs_collector on public.collection_schedule (garbage_collector_id);

-- Written by the collector app when a pickup is marked done.
create table if not exists public.pickup_log (
  pickup_log_id          integer generated by default as identity primary key,
  collection_schedule_id integer not null references public.collection_schedule (collection_schedule_id) on update cascade on delete cascade,
  garbage_collector_id   integer references public.garbage_collector (garbage_collector_id) on update cascade on delete set null,
  pickup_date            date not null,
  completed_at           timestamptz not null default now(),
  unique (collection_schedule_id, pickup_date)
);
create index if not exists pickup_log_date on public.pickup_log (pickup_date);

-- GPS pings from the collector app.
create table if not exists public.location_history (
  location_history_id  bigint generated by default as identity primary key,
  garbage_collector_id integer references public.garbage_collector (garbage_collector_id) on update cascade on delete cascade,
  latitude             numeric(10,8),
  longitude            numeric(11,8),
  "timestamp"          timestamptz not null default now()
);
create index if not exists location_history_latest on public.location_history (garbage_collector_id, location_history_id desc);

create table if not exists public.announcement (
  announcement_id     integer generated by default as identity primary key,
  lgu_admin_id        integer references public.lgu_admin (lgu_admin_id) on update cascade on delete set null,
  barangay_admin_id   integer references public.barangay_admin (barangay_admin_id) on update cascade on delete set null,
  title               varchar(150) not null,
  content             text not null,
  published_timestamp timestamptz not null default now(),
  expiry_date         date
);

create table if not exists public.feedback_report (
  feedback_report_id integer generated by default as identity primary key,
  lgu_admin_id  integer references public.lgu_admin (lgu_admin_id) on update cascade on delete set null,
  resident_id   integer references public.resident (resident_id) on update cascade on delete cascade,
  report_type   varchar(100),
  description   text,
  status        varchar(30) not null default 'Pending',
  latitude      numeric(10,8),
  longitude     numeric(11,8),
  created_at    timestamptz not null default now()
);
create index if not exists feedback_created on public.feedback_report (created_at);

-- One-time pickups outside the fixed schedule (managed by the Barangay Admin).
create table if not exists public.emergency_collection (
  emergency_collection_id integer generated by default as identity primary key,
  route_id             integer references public.route (route_id) on update cascade on delete set null,
  location_text        varchar(255) not null,
  latitude             numeric(10,8),
  longitude            numeric(11,8),
  collection_date      date not null,
  start_time           time not null,
  end_time             time,
  reason               varchar(255) not null,
  garbage_collector_id integer references public.garbage_collector (garbage_collector_id) on update cascade on delete set null,
  truck_id             integer references public.truck (truck_id) on update cascade on delete set null,
  status               varchar(20) not null default 'Scheduled' check (status in ('Scheduled', 'In progress', 'Completed', 'Cancelled')),
  notes                text,
  created_by           integer references public.barangay_admin (barangay_admin_id) on update cascade on delete set null,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  completed_at         timestamptz
);
create index if not exists emergency_date on public.emergency_collection (collection_date);

-- Log of saved reports ("Save to report log" on either panel's Reports page).
create table if not exists public.reports (
  report_id           integer generated by default as identity primary key,
  lgu_admin_id        integer references public.lgu_admin (lgu_admin_id) on update cascade on delete set null,
  barangay_admin_id   integer references public.barangay_admin (barangay_admin_id) on update cascade on delete set null,
  report_type         varchar(100),
  generated_timestamp timestamptz not null default now()
);

